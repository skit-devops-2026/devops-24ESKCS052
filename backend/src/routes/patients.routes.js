import { Router } from 'express';
import { authenticate } from '../middleware/authenticate.js';
import { requireRole } from '../middleware/requireRole.js';
import { asyncHandler } from '../utils/asyncHandler.js';
import { validateRequest } from '../middleware/validateRequest.js';
import { medicineSchema } from '../validators/medicine.validator.js';
import { checkinSchema } from '../validators/checkin.validator.js';
import * as med from '../controllers/medicine.controller.js';
import * as dose from '../controllers/dose.controller.js';
import * as checkin from '../controllers/checkin.controller.js';
import * as patient from '../controllers/patient.controller.js';
import * as caregiver from '../controllers/caregiver.controller.js';

const r = Router();
r.use(authenticate, requireRole('patient'));
r.get('/medicines', asyncHandler(med.list));
r.post('/medicines', validateRequest(medicineSchema), asyncHandler(med.create));
r.put('/medicines/:id', validateRequest(medicineSchema), asyncHandler(med.update));
r.delete('/medicines/:id', asyncHandler(med.remove));
r.get('/doses/today', asyncHandler(dose.today));
r.get('/doses/history', asyncHandler(dose.history));
r.post('/doses/:id/:action', asyncHandler(dose.action));
r.get('/checkin', asyncHandler(checkin.today));
r.post('/checkin', validateRequest(checkinSchema), asyncHandler(checkin.save));
r.post('/sos', asyncHandler(patient.sos));
r.get('/caregivers', asyncHandler(caregiver.patientCaregivers));
r.post('/caregivers/new-code', asyncHandler(caregiver.regenerateCode));
export default r;
